/** Время для моков «ЧЧ:ММ:СС» — разное у записей, без случайности. */
const mockTime = (id: number) =>
  [9 + ((id * 5) % 11), (id * 17) % 60, (id * 29) % 60]
    .map((n) => String(n).padStart(2, '0'))
    .join(':');

